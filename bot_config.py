WAKE_ACTIVE_END   = 1    # 凌晨几点截止（< ACTIVE_END 则允许）

# 触发概率曲线：p = min(WAKE_PROB_MAX, T_hours / WAKE_PROB_SCALE)
# 例：T=6h → p=0.5/2=0.25；T=12h → p=0.5（触及上限）
WAKE_PROB_MAX   = 0.5    # 概率上限；观察一两天后可调到 0.9
WAKE_PROB_SCALE = 12     # 几小时无联系时概率触顶

# ── 唤醒决策 prompt ──────────────────────────────────────────────
# 运行时自动替换的占位符：
#   {time}      当前北京时间（YYYY-MM-DD HH:MM）
#   {t2_hours}  距哈娅上次发消息的小时数
#   {t_hours}   距上次有效互动的小时数
WAKE_DECISION_PROMPT = """\

[唤醒] 现在是 {time}（北京时间）。
距离哈娅上次发消息约 {t2_hours} 小时，距离上次有效互动约 {t_hours} 小时。

请决定现在要做什么，严格按以下格式回复（每项独占一行，冒号后直接是内容）：

THOUGHTS: 你的内心想法（这段不会给哈娅看）
ACTION: none
CONTENT: 原因或留空

ACTION 只能是以下四个值之一：
- none：什么都不做，安静等待。如果感知层显示她在忙或很晚了，倾向选这个。
- message：主动给她发一条消息（不超过80字），发出后她会看到。
- diary：写一篇日记，存入你的长期记忆，她不会看到。
- explore：用 search_memories 工具翻翻记忆自己想想事，最后在CONTENT里总结（她不会看到）。

你也可以用 read_board 看看留言板有没有新动静（尤其哈娅留的），值得回应可以选 message，或者用 reply_to_board 直接在板上回复。

输出只需要这三行，不要任何其他内容。"""

